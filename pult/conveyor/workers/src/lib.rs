//! `pult-conveyor-workers` — воркеры конвейера Story 1.4 (FR-3): вертикаль
//! адаптер → RabbitMQ (quorum) → worker → PG.
//!
//! Две роли одного бинарника (спека 1.4, AD-23 — stateless):
//! - **Оркестратор синка** ([`orchestrator`]): планировщик организаций с
//!   verified-WB и незавершённым `initial_orders`, прогон окон дат
//!   (новые окна первее — «канбан жив» за минуты), публикация событий
//!   AD-22, чекпоинты после каждого окна (AD-3);
//! - **Консьюмер** ([`consumer`]): подписка на quorum-очередь, идемпотентная
//!   проекция в PG (AD-15: idem UNIQUE + барьер ревизий), ack только после
//!   коммита (at-least-once поглощается идемпотентностью).
//!
//! Инфраструктурные закрытия портов: [`store`] (sqlx: проекция + чекпоинты)
//! и [`amqp`] (lapin: publisher с confirms + консьюмер). Сериализация
//! событий — [`dto`] (serde — компоновочный слой конвейера; домен без serde).
//!
//! Юнит/интеграционные тесты цикла — на in-memory фейках портов (спека:
//! lapin и PG — в CI e2e, не в юнитах).
//!
//! Дедуп, fair-scheduling слотов по организациям — AD-15/AD-6.

